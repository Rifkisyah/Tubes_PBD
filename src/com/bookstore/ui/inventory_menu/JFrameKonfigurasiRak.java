    public String generateIdRak() {
        Rak rak = new Rak(); // Pastikan class ini memiliki method `cekIdRakSudahAda`
        String prefix = "R";
        int counter = 1;
        String newId;

        while (true) {
            newId = prefix + String.format("%02d", counter); // RK001, RK002, ...
            if (!rak.cekIdRakSudahAda(newId)) {
                break;
            }
            counter++;
        }

        return newId;
    }



