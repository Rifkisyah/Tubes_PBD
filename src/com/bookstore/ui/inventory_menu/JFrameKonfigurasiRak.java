    private void JButton_mengahpusRakActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_JButton_mengahpusRakActionPerformed
        if(JOptionPane.showConfirmDialog(this, "Apakah Kamu Yakin Ingin Menghapus Rak ini?", "konfirmasi hapus", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION){
            String code = JTextfield_kodeRak.getText().trim();
            String name = JTextfield_namaRak.getText().trim();
            String location = JTextfield_lokasiRak.getText().trim();

            if (code.equals("")) {
                JOptionPane.showMessageDialog(this, "Kode rak Masih Kosong!", "Terjadi Masalah", JOptionPane.ERROR_MESSAGE);
                return;
            } else if (name.equals("")) {
                JOptionPane.showMessageDialog(this, "Nama rak Masih Kosong!", "Terjadi Masalah", JOptionPane.ERROR_MESSAGE);
                return;
            } else if (location.equals("")) {
                JOptionPane.showMessageDialog(this, "Lokasi rak Masih Kosong!", "Terjadi Masalah", JOptionPane.ERROR_MESSAGE);
                return;
            }

            try {
                Rak rak = new Rak();
                rak.getSemuaDataDariKodeRak(code);

                if (!rak.getResultSet().next()) {
                    JOptionPane.showMessageDialog(this, "Rak Tidak Ada!", "Gagal Menghapus Rak", JOptionPane.ERROR_MESSAGE);
                } else {
                    rak.updateNullKetikaRakDihapus(code);
                    rak.menghapusRak(code);

                    if (rak.getAffectedRow() > 0) {
                        tableModel.getDataVector().removeAllElements();
                        tableModel.fireTableDataChanged();

                        JTextfield_kodeRak.setText("");
                        JTextfield_namaRak.setText("");
                        JTextfield_lokasiRak.setText("");
                        getDataTable();

                        JOptionPane.showMessageDialog(this, "Rak Berhasil Dihapus", "Berhasil Menghapus Rak", JOptionPane.INFORMATION_MESSAGE);
                    } else {
                        JOptionPane.showMessageDialog(this, "Rak Tidak Ada!", "Gagal Menghapus Rak", JOptionPane.ERROR_MESSAGE);
                    }
                }
            } catch (SQLException ex) {
                ex.printStackTrace();
            }
        }
    }//GEN-LAST:event_JButton_mengahpusRakActionPerformed

    private void JButton_menambahkanRakActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_JButton_menambahkanRakActionPerformed
        String code = JTextfield_kodeRak.getText().trim();
        String name = JTextfield_namaRak.getText().trim();
        String location = JTextfield_lokasiRak.getText().trim();

        if(code.equals("")){
            JOptionPane.showMessageDialog(this, "Kode rak Masih Kosong!", "Terjadi Masalah", JOptionPane.ERROR_MESSAGE);
            return;
        } else if(name.equals("")){
            JOptionPane.showMessageDialog(this, "Nama rak Masih Kosong!", "Terjadi Masalah", JOptionPane.ERROR_MESSAGE);
            return;
        } else if(location.equals("")){
            JOptionPane.showMessageDialog(this, "Lokasi rak Masih Kosong!", "Terjadi Masalah", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            Rak rak = new Rak();
            rak.getSemuaDataDariKodeRak(code);
            
            if(rak.getResultSet().next()){
                // Jika ada, lakukan update nama dan lokasi
                rak.memperbaruiDataRak(name, location, code);
                    JTextfield_kodeRak.setText("");
                    JTextfield_namaRak.setText("");
                    JTextfield_lokasiRak.setText("");
                    getDataTable();
                        
                JOptionPane.showMessageDialog(this, "Data Rak Berhasil Diperbarui", "Berhasil", JOptionPane.INFORMATION_MESSAGE);
            } else {
                // Jika tidak ada, insert data baru
                rak.menambahDataRak(code, name, location);
                JTextfield_kodeRak.setText("");
                JTextfield_lokasiRak.setText("");
                JTextfield_namaRak.setText("");
                getDataTable();
                
                JOptionPane.showMessageDialog(this, "Rak Baru Berhasil Ditambahkan", "Berhasil", JOptionPane.INFORMATION_MESSAGE);
            }

        } catch (SQLException ex){
            ex.printStackTrace();
            clearInput();
            JOptionPane.showMessageDialog(this, "Rak Sudah Ada!", "Gagal Menambahkan Rak", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_JButton_menambahkanRakActionPerformed

