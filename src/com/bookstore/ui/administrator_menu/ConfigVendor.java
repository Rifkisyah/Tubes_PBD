    private void deleteVendorButonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteVendorButonActionPerformed
        int deleting = JOptionPane.showConfirmDialog(this, "Apakah Kamu Yakin Ingin Menghapus Data Ini?");
        if(deleting == JOptionPane.YES_OPTION){
            String idRole = field_id_vendor.getText().trim();
            if(idRole.isEmpty()){
                JOptionPane.showMessageDialog(null, "Nama Role Masih Kosong!");
                field_id_vendor.requestFocus();
            } else {
                try {

                    querySelector.deleteByKey("T_Role", "id_role", idRole);

                    if (querySelector.getAffectedRows() > 0) {
                        model.getDataVector().removeAllElements();
                        model.fireTableDataChanged();

                        field_id_vendor.setText("");
                        field_nama_vendor.setText("");
                        field_kontak_vendor.setText("");
                        field_alamat_vendor.setText("");
                        
                        dataVendorToTabel();
                        JOptionPane.showMessageDialog(null, "Data Berhasil Dihapus");
                    } else {
                        JOptionPane.showMessageDialog(null, "Vendor Tidak Ada!");
                    }
                } catch (SQLException | ClassNotFoundException ex) {
                    Logger.getLogger(MaintenanceRolePegawai.class.getName()).log(Level.SEVERE, null, ex);
                }
            }
        } else {
            JOptionPane.showMessageDialog(null, "data Berhasil Dihapus");
        }
    }//GEN-LAST:event_deleteVendorButonActionPerformed

