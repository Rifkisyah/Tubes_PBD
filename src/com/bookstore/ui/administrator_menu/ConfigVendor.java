    public void dataVendorToTabel(){
        this.querySelector = new QuerySelector();

        try{
            querySelector.selectAllFromTable("T_Vendor");

            model.setRowCount(0);
            
            while (querySelector.getResultSet().next()) {    
            Object[] fieldx = new Object[4];
                fieldx[0] = querySelector.getResultSet().getString("id_vendor");
                fieldx[1] = querySelector.getResultSet().getString("Nama_vendor");
                fieldx[2] = querySelector.getResultSet().getString("alamat_vendor");
                fieldx[3] = querySelector.getResultSet().getString("kontak_vendor");
                model.addRow(fieldx);
            }
        } catch (SQLException | ClassNotFoundException  e){
            e.printStackTrace();
        }
    }
    
