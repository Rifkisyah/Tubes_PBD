    private void addVendorButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addVendorButtonActionPerformed
        String vendorId = field_id_vendor.getText().trim();
        String vendorName = field_nama_vendor.getText().trim();
        String vendorContact = field_kontak_vendor.getText().trim();
        String vendorAddress = field_alamat_vendor.getText().trim();
        
        try {
            if (vendorId.isEmpty() || vendorName.isEmpty() || vendorContact.isEmpty() || vendorAddress.isEmpty()) {
                JOptionPane.showMessageDialog(null, "ID atau Nama Role masih kosong!");
                field_id_vendor.requestFocus();
                return;
            }
            querySelector.countDataByColumn("T_Vendor", "id_vendor", vendorId);

                if (querySelector.getAffectedRows() > 0) {
                    if(JOptionPane.showConfirmDialog(this, "Data Vendor Sudah Ada! Apakah Kamu mau Uodate Data ini?", "info", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION){
                        field_id_vendor.setEnabled(false);
                        
                        querySelector.updateThreeColumns("T_Vendor", "nama_vendor", vendorName, "kontak_vendor", vendorContact, "alamat_vendor", vendorAddress, "id_vendor", vendorId);
                        
                        if (querySelector.getAffectedRows() > 0) {
                            field_id_vendor.setText("");
                            field_nama_vendor.setText("");
                            field_kontak_vendor.setText("");
                            field_alamat_vendor.setText("");
                            
                            dataVendorToTabel();
                            field_id_vendor.setEnabled(true);
                            JOptionPane.showMessageDialog(null, "Data Berhasil Diperbarui");
                        } else {
                            JOptionPane.showMessageDialog(null, "Data Gagal Diperbarui");
                        }
                    }
                } else {
                    querySelector.insertFourColumns("T_Vendor", "id_vendor", "nama_vendor", "alamat_vendor", "kontak_vendor", vendorId, vendorName, vendorContact, vendorAddress);

                    if (querySelector.getAffectedRows() > 0) {
                        model.getDataVector().removeAllElements();
                        model.fireTableDataChanged();
          
                        field_id_vendor.setText("");
                        field_nama_vendor.setText("");
                        field_kontak_vendor.setText("");
                        field_alamat_vendor.setText("");

                       dataVendorToTabel();
                        
                        JOptionPane.showMessageDialog(null, "Data Berhasil Disimpan");
                    } else {
                        JOptionPane.showMessageDialog(null, "Data Gagal Disimpan");
                    }
                }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "SQL Error: " + e.getMessage());
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(MaintenanceRolePegawai.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_addVendorButtonActionPerformed

