    private void JButton_saveNewRoleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_JButton_saveNewRoleActionPerformed
        String rolename = JTextfield_namaRole.getText().trim();
        String idRole = JTextfield_idRole.getText().trim();
        Role role = new Role();
        
        if (rolename.isEmpty() || idRole.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Input masih kosong!");
            JTextfield_idRole.requestFocus();
            return;
        }
        role.getJumlahDataBerdasarkanIdRole(idRole);
        
        if (role.getAffectedRow() > 0) {
            if(JOptionPane.showConfirmDialog(this, "Role Sudah Ada! Apakah Kamu mau Update Data ini?", "info", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION){
                role.updateRole(rolename, idRole);
                
                if (role.getAffectedRow() > 0) {
                    resetInputData();
                    dataKeTabel();
                    JButton_saveNewRole.setText("Tambahkan");
                    JOptionPane.showMessageDialog(null, "Role Berhasil Diperbarui");
                
                } else {
                    JOptionPane.showMessageDialog(null, "Role Gagal Diperbarui");
                    resetInputData();
                }
            }
        } else {
            role.memasukanRoleBaru(idRole, rolename);
            if(role.getAffectedRow()> 0) {
                model.getDataVector().removeAllElements();
                model.fireTableDataChanged();
                resetInputData();
                dataKeTabel();
                JOptionPane.showMessageDialog(null, "Role Berhasil Disimpan");
            
            } else {
                JOptionPane.showMessageDialog(null, "Role Gagal Disimpan");
            }
        }
    }//GEN-LAST:event_JButton_saveNewRoleActionPerformed

    private void JButton_deleteRoleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_JButton_deleteRoleActionPerformed
        int deleting = JOptionPane.showConfirmDialog(this, "Apakah Kamu Yakin Ingin Menghapus Data Ini?", "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);
        
        if(deleting == JOptionPane.YES_OPTION){
            String idRole = JTextfield_idRole.getText().trim();
            Role role = new Role();

            if(idRole.isEmpty()){
                JOptionPane.showMessageDialog(null, "Nama Role Masih Kosong!");
                JTextfield_idRole.requestFocus();
            } else {
                role.hapusRole(idRole);
                if (role.getAffectedRow() > 0) {
                    model.getDataVector().removeAllElements();
                    model.fireTableDataChanged();

                    resetInputData();

                    dataKeTabel();
                    JOptionPane.showMessageDialog(null, "Data Berhasil Dihapus");
                } else {
                    JOptionPane.showMessageDialog(null, "ID Tidak Ditemukan atau Tidak Dihapus");
                }
            }
        }
    }//GEN-LAST:event_JButton_deleteRoleActionPerformed

