    public void dataKeTabel(){
        Role role = new Role();

        try{
            role.getSemuaDataRole();
            
            model.setRowCount(0);

            while (role.getResultSet().next()) {    
            Object[] fieldx = new Object[3];
                fieldx[0] = role.getResultSet().getString("Id_Role");
                fieldx[1] = role.getResultSet().getString("Nama_Role");
                fieldx[2] = role.getResultSet().getString("Tanggal_Buat");
                model.addRow(fieldx);
            }
        } catch (SQLException  e){
            e.printStackTrace();
        }
    }
    
