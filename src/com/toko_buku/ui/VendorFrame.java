    private void TombolSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_TombolSimpanActionPerformed
        try {
            DbConnection ctd = new DbConnection();

            String idVendor = FieldInputIdVendor.getText().trim();
            String namaVendor = FieldInputNamaVendor.getText().trim();
            String alamatVendor = FieldInputAlamatVendor.getText().trim();
            String kontakVendor = FieldinputKontakVendor.getText().trim();
        
        if (namaVendor.isEmpty() || idVendor.isEmpty() || alamatVendor.isEmpty() || kontakVendor.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Terdapat Data Yang Masih Kosong!");
                FieldInputIdVendor.requestFocus();
            } else {
                Connection conn = ctd.getConnection();

                // Cek apakah data dengan ISBN sudah ada
                String checkQuery = "SELECT COUNT(*) FROM T_Vendor WHERE Id_Vendor = ?";
                try (PreparedStatement checkStmt = conn.prepareStatement(checkQuery)) {
                    checkStmt.setString(1, idVendor);
                    ResultSet rs = checkStmt.executeQuery();
                    rs.next();
                    int count = rs.getInt(1);

                    if (count > 0) {
                        // UPDATE jika data sudah ada
                        String updateQuery = "UPDATE T_Vendor SET Nama_Vendor = ?, Alamat_Vendor = ?, Kontak_Vendor = ? WHERE Id_Vendor = ?";
                        try (PreparedStatement preparedStatement = conn.prepareStatement(updateQuery)) {
                            preparedStatement.setString(1, namaVendor);
                            preparedStatement.setString(2, alamatVendor);
                            preparedStatement.setString(3, kontakVendor);
                            preparedStatement.setString(4, idVendor);

                            int dataUpdated = preparedStatement.executeUpdate();

                            if (dataUpdated > 0) {
                                model.getDataVector().removeAllElements();
                                model.fireTableDataChanged();
                                clearinput();
                                viewRole(); // Pastikan fungsi ini sesuai konteksnya
                                JOptionPane.showMessageDialog(null, "Data Berhasil Diperbarui");
                            } else {
                                JOptionPane.showMessageDialog(null, "Data Gagal Diperbarui");
                            }
                        }

                    } else {
                        // INSERT jika data belum ada
                        String insertQuery = "INSERT INTO T_Vendor (Id_Vendor, Nama_Vendor, Alamat_Vendor, Kontak_Vendor) VALUES (?, ?, ?, ?)";
                        try (PreparedStatement preparedStatement = conn.prepareStatement(insertQuery)) {
                            preparedStatement.setString(1, idVendor);
                            preparedStatement.setString(2, namaVendor);
                            preparedStatement.setString(3, alamatVendor);
                            preparedStatement.setString(4, kontakVendor);


                            int dataInserted = preparedStatement.executeUpdate();

                            if (dataInserted > 0) {
                                model.getDataVector().removeAllElements();
                                model.fireTableDataChanged();
                                clearinput();
                                viewRole();
                                JOptionPane.showMessageDialog(null, "Data Berhasil Disimpan");
                            } else {
                                JOptionPane.showMessageDialog(null, "Data Gagal Disimpan");
                            }
                        }
                    }
                }
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "SQL Error: " + e.getMessage());
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(VendorFrame.class.getName()).log(Level.SEVERE, null, ex);
        }                           
    }//GEN-LAST:event_TombolSimpanActionPerformed

