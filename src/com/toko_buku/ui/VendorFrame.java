    public void viewRole() throws ClassNotFoundException{
        DbConnection ctd = new DbConnection();
        try{
            Connection conn = ctd.getConnection();
            Statement statement = (Statement) conn.createStatement();
            String query = "SELECT *FROM T_Vendor";
            PreparedStatement preparedStatement = conn.prepareStatement(query);
            ResultSet rs = preparedStatement.executeQuery();
            
            while (rs.next()) {
                
            Object[] fieldx = new Object[4];
            fieldx[0] = rs.getString("Id_Vendor");
            fieldx[1] = rs.getString("Nama_Vendor");
            fieldx[2] = rs.getString("Alamat_Vendor");
            fieldx[3] = rs.getString("Kontak_Vendor");
                model.addRow(fieldx);
            }
        } catch (SQLException e){
            e.printStackTrace();
        }
    }
    
    private void deleteData(){
        String idVendor = FieldInputIdVendor.getText().trim();
        String namaVendor = FieldInputNamaVendor.getText().trim();
        String alamatVendor = FieldInputAlamatVendor.getText().trim();
        String kontakVendor = FieldinputKontakVendor.getText().trim();
        
        if (namaVendor.isEmpty() || idVendor.isEmpty() || alamatVendor.isEmpty() || kontakVendor.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Terdapat Data Yang Masih Kosong!");
                FieldInputIdVendor.requestFocus();
        } else {
            try {
                DbConnection ctd = new DbConnection();
                Connection conn = ctd.getConnection();
                String query = "DELETE FROM T_Vendor WHERE Id_Vendor=?";
                PreparedStatement preparedStatement = conn.prepareStatement(query);
                preparedStatement.setString(1, idVendor);
                preparedStatement.executeUpdate();
                model.getDataVector().removeAllElements();
                model.fireTableDataChanged();
                clearinput();
                viewRole();
                JOptionPane.showMessageDialog(null, "Vendor Berhasil Dihapus");
                
            } catch (ClassNotFoundException e){
                Logger.getLogger(VendorFrame.class.getName()).log(Level.SEVERE, null, e);
            } catch (SQLException ex) {
                Logger.getLogger(VendorFrame.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }
    
