    private void jButtonSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSimpanActionPerformed
        try{
            String idProduk = jTextFieldIdProduk.getText();
            String namaProduk = jTextFieldNamaProduk.getText();
            String hargaProduk = jTextFieldPriceProduk.getText();
            String totalStokProduk = jTextFieldTotalStockProduk.getText();

            DbConnection dbc = new DbConnection();

            if(idProduk.equals("")){
                JOptionPane.showMessageDialog(this, "id Produk Masih Kosong!", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if(namaProduk.equals("")){
                JOptionPane.showMessageDialog(this, "Nama Produk Masih Kosong!", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if(hargaProduk.equals("")){
                JOptionPane.showMessageDialog(this, "Harga Produk Masih Kosong!", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if(totalStokProduk.equals("")){
                JOptionPane.showMessageDialog(this, "Total Stok Produk Masih Kosong!", "Warning", JOptionPane.WARNING_MESSAGE);
            } else {

                // check first
                String queryCheck = "SELECT *FROM tmasterid WHERE itemid = ?";
                PreparedStatement pstmt = dbc.getConnection().prepareStatement(queryCheck);
                pstmt.setString(1, idProduk);
                ResultSet rslt = pstmt.executeQuery();

                if(rslt.next()){

                    if(JOptionPane.showConfirmDialog(this, "Produk sudah ada, apakah yakin ingin update data Produk?", "konfirmasi", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION){

                        String queryUpdate = "UPDATE tmasterid SET namaproduk = ?, price = ?, totalstok = ? WHERE itemid = ?";
                        pstmt = dbc.getConnection().prepareStatement(queryUpdate);
                        pstmt.setString(1, namaProduk);
                        pstmt.setString(2, hargaProduk);
                        pstmt.setString(3, totalStokProduk);
                        pstmt.setString(4, idProduk);

                        int affected = pstmt.executeUpdate();

                        if(affected > 0){
                            clearInput();
                            setDataTable();
                            JOptionPane.showMessageDialog(this, "Data Produk berhasil di Update!", "informasi", JOptionPane.INFORMATION_MESSAGE);
                        }

                    }
                } else {

                    String queryInsert = "INSERT INTO tmasterid(itemid, namaproduk, price, totalstok) values(?, ?, ?, ?)";
                    pstmt = dbc.getConnection().prepareStatement(queryInsert);
                    pstmt.setString(1, idProduk);
                    pstmt.setString(2, namaProduk);
                    pstmt.setString(3, hargaProduk);
                    pstmt.setString(4, totalStokProduk);

                    int affected = pstmt.executeUpdate();

                    if(affected > 0){
                        clearInput();
                        setDataTable();
                        JOptionPane.showMessageDialog(this, "Data Produk berhasil di Tambahkan!", "informasi", JOptionPane.INFORMATION_MESSAGE);
                    }

                }
            }

        } catch (SQLException ex){
            ex.printStackTrace();
        }
    }//GEN-LAST:event_jButtonSimpanActionPerformed

