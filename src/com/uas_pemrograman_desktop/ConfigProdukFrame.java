    private void setDataTable(){
        try{
            DbConnection dbc = new DbConnection();
            
            String query = "SELECT * FROM tmasterid"; 
            PreparedStatement pstmt = dbc.getConnection().prepareStatement(query);
            ResultSet rslt = pstmt.executeQuery();
                    
            dtm.setRowCount(0);
            
            while (rslt.next()) {    
            Object[] fieldx = new Object[4];
                fieldx[0] = rslt.getString("itemid");
                fieldx[1] = rslt.getString("namaproduk");
                fieldx[2] = rslt.getString("price");
                fieldx[3] = rslt.getString("totalstok");
                dtm.addRow(fieldx);
            }
        } catch (SQLException  e){
            e.printStackTrace();
        }
    }
    
